void main(){
  // with var the compiler defines the proper type
  // int
  var numberOfDays = 7;
  // double
  var workingHours = 40.5;
  // bool
  var bankHoliday = true;
  // String
  var employeeName = "John Smith";
  print(numberOfDays); 
  print(workingHours); 
  print(bankHoliday); 
  print(employeeName); 
}